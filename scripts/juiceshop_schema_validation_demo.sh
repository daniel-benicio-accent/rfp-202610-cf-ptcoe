#!/usr/bin/env bash
#
# Schema validation demo harness for OWASP Juice Shop and the go-httpbin demo
# API behind Cloudflare.
#
# Sends pairs of compliant / non-compliant requests and reports whether each
# one was stopped at the Cloudflare edge or reached the origin. It also sends
# front-end calls that have no schema, which must keep reaching the origin as
# enforcement tightens.
#
# Usage:
#   BASE_URL=https://app-pt-cybersec-coe-juiceshop.pt-accenture.cftenant.com \
#   API_BASE_URL=https://api.<zone> \
#     ./juiceshop_schema_validation_demo.sh [schema.json]
#
# Schema mode: pass an OpenAPI 3.0 JSON file (for example a schema exported
# from Cloudflare API Shield) and the script runs only the operations in that
# file instead of the built-in cases below. For each operation it sends one
# compliant request, built from the examples, defaults and constraints in the
# schema. It then sends one non-compliant request for each constraint it can
# break: number or boolean type, minimum, maximum, pattern, enum, maxLength,
# a missing required query parameter or body field, and an undeclared body
# field where additionalProperties is false. It covers path and query
# parameters and top-level JSON body fields. A learned schema types every
# variable as a plain string, so it yields compliant requests only.
# Requests go to BASE_URL, or to the schema's servers[0].url when BASE_URL is
# unset. API_BASE_URL and FALLTHROUGH do not apply. A client certificate, if
# set, goes with every request unless SKIP_MTLS=on. Requires jq.
#
# API_BASE_URL is the go-httpbin hostname from httpbin-api.yaml. Without it,
# the httpbin cases are skipped. Its /anything/partner/ route requires mTLS:
# set API_CLIENT_CERT and API_CLIENT_KEY (PEM files) to run those two cases,
# or SKIP_MTLS=on to leave them out even when a certificate is set.
#
# Set FALLTHROUGH=on once a fallthrough rule blocks requests that match no
# saved endpoint (scope it to /api/ and /rest/, or it blocks the front end
# too). Until then the undeclared-endpoint case is skipped.
#
# Note: compliant requests may still get 4xx from Juice Shop itself (wrong
# credentials, missing token, wrong captcha). That is expected: what matters
# is that they REACHED the origin instead of being blocked by Cloudflare.

set -euo pipefail

readonly SCHEMA_FILE="${1:-}"
if [[ -n "${SCHEMA_FILE}" ]]; then
  readonly BASE_URL="${BASE_URL:-}"
else
  readonly BASE_URL="${BASE_URL:?Set BASE_URL to the public Cloudflare-proxied URL}"
fi
readonly API_BASE_URL="${API_BASE_URL:-}"
readonly API_CLIENT_CERT="${API_CLIENT_CERT:-}"
readonly API_CLIENT_KEY="${API_CLIENT_KEY:-}"
readonly SKIP_MTLS="${SKIP_MTLS:-off}"
readonly FALLTHROUGH="${FALLTHROUGH:-off}"
readonly WORK_DIR="$(mktemp -d)"
trap 'rm -rf "${WORK_DIR}"' EXIT

failures=0

# Where the next run_case calls go, and extra curl arguments for them
# (the client certificate for mTLS routes). main() switches these per section.
case_base="${BASE_URL}"
case_extra_args=()

# Width of the CASE column. Schema mode widens it to fit long paths.
case_width=48

print_row() {
  printf "%-${case_width}s %-10s %-6s %-12s %s\n" "$@"
}

print_header() {
  print_row "CASE" "EXPECTED" "HTTP" "RESULT" "CF-RAY"
  printf '%*s\n' "$((case_width + 52))" '' | tr ' ' '-'
}

# Classifies a response as blocked by Cloudflare when it is a 403 generated by
# the edge. Browsers get an HTML block page that names Cloudflare; curl gets a
# plain-text body such as "error code: 1020". Both forms count.
classify_response() {
  local status="$1" body_file="$2"
  if [[ "${status}" == "403" ]] \
    && grep -qiE '^error code: [0-9]+|cloudflare' "${body_file}"; then
    echo "edge-block"
  else
    echo "origin"
  fi
}

run_case() {
  local name="$1" expected="$2" method="$3" path="$4" body="${5:-}"
  local headers_file="${WORK_DIR}/headers" body_file="${WORK_DIR}/body"
  local -a curl_args=(-s -o "${body_file}" -D "${headers_file}" -w '%{http_code}' -X "${method}"
    ${case_extra_args[@]+"${case_extra_args[@]}"})

  if [[ -n "${body}" ]]; then
    curl_args+=(-H 'Content-Type: application/json' --data "${body}")
  fi

  local status
  status="$(curl "${curl_args[@]}" "${case_base}${path}")"

  local actual ray verdict
  actual="$(classify_response "${status}" "${body_file}")"
  ray="$(grep -i '^cf-ray:' "${headers_file}" | awk '{print $2}' | tr -d '\r' || true)"

  if [[ "${actual}" == "${expected}" ]]; then
    verdict="PASS"
  else
    verdict="FAIL(${actual})"
    failures=$((failures + 1))
  fi

  print_row "${name}" "${expected}" "${status}" "${verdict}" "${ray:--}"
}

skip_case() {
  local name="$1" expected="$2" reason="$3"
  print_row "${name}" "${expected}" "-" "SKIP" "(${reason})"
}

# Turns an OpenAPI 3.0 JSON document into test cases. Each output line is one
# case, its fields separated by 0x1f:
#   run  | name | expected | method | path and query | JSON body or empty
#   skip | name | expected | -      | -              | reason
readonly SCHEMA_CASES_JQ="$(cat <<'JQ'
. as $root
| def deref:
    if type == "object" and has("$ref") then
      .["$ref"] as $ref
      | $root
      | getpath($ref | ltrimstr("#/") | split("/") | map(gsub("~1"; "/") | gsub("~0"; "~")))
      | deref
    else . end;
  def type_of: (.type // null) | if type == "array" then map(select(. != "null"))[0] else . end;
  def is_num: . == "integer" or . == "number";
  def matches($pattern): try test($pattern) catch false;
  def fits($s): length >= ($s.minLength // 0) and ($s.maxLength == null or length <= $s.maxLength);

  # A value the schema accepts, or null when none can be derived.
  def sample:
    deref as $s | ($s | type_of) as $t
    | if ($s | type) != "object" then null
      elif $s.example != null then $s.example
      elif $s.default != null then $s.default
      elif ($s.enum | type) == "array" and ($s.enum | length) > 0 then $s.enum[0]
      elif ($s.oneOf // $s.anyOf) != null then ($s.oneOf // $s.anyOf)[0] | sample
      elif $s.allOf != null then
        [$s.allOf[] | sample] | if any(.[]; . == null) then null else add end
      elif $t | is_num then
        if $s.minimum != null then $s.minimum + (if $s.exclusiveMinimum == true then 1 else 0 end)
        elif $s.maximum != null and $s.maximum < 1 then
          $s.maximum - (if $s.exclusiveMaximum == true then 1 else 0 end)
        else 1 end
      elif $t == "boolean" then true
      elif $t == "array" then ($s.items // {} | sample) as $i | if $i == null then null else [$i] end
      elif $t == "object" or $s.properties != null then
        ($s.required // []) as $req
        | [($s.properties // {}) | to_entries[] | {key, value: (.value | sample)}]
        | if any(.[]; .value == null and (.key | IN($req[]))) then null
          else map(select(.value != null)) | from_entries end
      elif $t == "string" or $t == null then
        ({"email": "user@example.com", "uuid": "00000000-0000-4000-8000-000000000000",
          "date": "2026-01-01", "date-time": "2026-01-01T00:00:00Z"}[$s.format // ""]) as $f
        | if $f != null then $f
          elif $s.pattern != null then
            first(("1", "42", "abc", "acme-corp", "ABC-1234", "abc123", "A1", "2026-01-01",
                   "user@example.com") | select(matches($s.pattern) and fits($s))) // null
          elif ($s.minLength // 0) > 1 then "a" * $s.minLength
          else "1" end
      else null end;

  # Values the schema rejects, one per constraint. Path and query values are
  # strings on the wire, so only body fields get the "not a string" check.
  def violations($in_body):
    deref as $s | ($s | type_of) as $t
    | if ($s | type) != "object" then empty else
        (if $t | is_num then {label: "not a number", value: "abc"}
         elif $t == "boolean" then {label: "not a boolean", value: "maybe"}
         elif $t == "string" and $in_body then {label: "not a string", value: 12345}
         else empty end),
        (if $s.maximum != null then
           {label: "above maximum", value: ($s.maximum + (if $s.exclusiveMaximum == true then 0 else 1 end))}
         else empty end),
        (if $s.minimum != null then
           {label: "below minimum", value: ($s.minimum - (if $s.exclusiveMinimum == true then 0 else 1 end))}
         else empty end),
        (if ($s.enum | type) == "array" then {label: "not in enum", value: "not-in-enum"} else empty end),
        (if $s.pattern != null then
           first(("Invalid_Value", "0", "a") | select(matches($s.pattern) | not))
           | {label: "breaks pattern", value: .}
         else empty end),
        (if $s.maxLength != null then {label: "too long", value: ("a" * ($s.maxLength + 1))} else empty end)
      end;

  # Path with its variables filled in, plus the query string. Variables the
  # schema does not declare get "1".
  def target($path; $pathv; $query):
    (reduce ($pathv | to_entries[]) as $e ($path; split("{\($e.key)}") | join($e.value | tostring | @uri))
     | gsub("\\{[^}]*\\}"; "1"))
    + ([$query | to_entries[] | .key as $k | (.value | if type == "array" then .[] else . end)
        | "\($k | @uri)=\(tostring | @uri)"] | join("&") | if . == "" then "" else "?" + . end);

  def body_of($op):
    ($op.requestBody // null | deref) as $rb
    | if $rb == null then {state: "none"}
      else
        ([($rb.content // {}) | to_entries[] | select(.key | test("json"))] | first | .value) as $media
        | (if $media == null then null
           elif $media.example != null then $media.example
           else ($media.schema // {} | sample) end) as $value
        | if $value != null then
            {state: "ok", value: $value, schema: ($media.schema // {} | deref), json: ($value | tojson)}
          elif $rb.required != true then {state: "none"}
          elif $media == null then
            {state: "skip", reason: "body is \(($rb.content // {}) | keys | join(", ")), not JSON"}
          else {state: "skip", reason: "no sample body; add an example"} end
      end;

  $root.paths | to_entries[] | .key as $path | .value as $item
  | $item | to_entries[]
  | select(.key | IN("get", "put", "post", "delete", "patch", "head", "options", "trace"))
  | (.key | ascii_upcase) as $method | .value as $op
  | "\($method) \($path)" as $name
  | ([($item.parameters // [])[], ($op.parameters // [])[]] | map(deref)
     | map(select(.in == "path" or .in == "query"))
     | group_by([.in, .name]) | map(last)
     | map(. + {value: (if .example != null then .example else (.schema // {} | sample) end)})) as $params
  | ($params | map(select(.in == "path")) | map({key: .name, value}) | from_entries) as $pathv
  | ($params | map(select(.in == "query" and .value != null)) | map({key: .name, value}) | from_entries) as $query
  | ($params | map(select(.value == null and (.in == "path" or .required == true)) | .name)) as $unsampled
  | body_of($op) as $body
  | ($body.json // "") as $json
  | target($path; $pathv; $query) as $target
  | if $method == "HEAD" then
      ["skip", "\($name): valid", "origin", "-", "-", "HEAD has no body to tell an edge block apart"]
    elif ($unsampled | length) > 0 then
      ["skip", "\($name): valid", "origin", "-", "-", "no sample for \($unsampled | join(", ")); add an example"]
    elif $body.state == "skip" then
      ["skip", "\($name): valid", "origin", "-", "-", $body.reason]
    else
      ["run", "\($name): valid", "origin", $method, $target, $json],
      ($params[] as $p | $p.schema // {} | violations(false)
        | ["run", "\($name): \($p.name) \(.label)", "edge-block", $method,
           (if $p.in == "path" then target($path; $pathv + {($p.name): .value}; $query)
            else target($path; $pathv; $query + {($p.name): .value}) end), $json]),
      (($params[] | select(.in == "query" and .required == true)) as $p
        | ["run", "\($name): \($p.name) missing", "edge-block", $method,
           target($path; $pathv; $query | del(.[$p.name])), $json]),
      (if $body.state == "ok" and ($body.value | type) == "object" then
         $body.schema as $bs
         | ((($bs.properties // {}) | to_entries[]) as $e
              | $e.value | violations(true)
              | ["run", "\($name): \($e.key) \(.label)", "edge-block", $method, $target,
                 ($body.value + {($e.key): .value} | tojson)]),
           (($bs.required // [])[] | select(. as $r | $body.value | has($r)) as $r
              | ["run", "\($name): \($r) missing", "edge-block", $method, $target,
                 ($body.value | del(.[$r]) | tojson)]),
           (if $bs.additionalProperties == false then
              ["run", "\($name): undeclared field", "edge-block", $method, $target,
               ($body.value + {unexpected_field: 0} | tojson)]
            else empty end)
       else empty end)
    end
  | join("\u001f")
JQ
)"

# Schema mode: runs only the cases derived from an OpenAPI JSON document.
run_schema_cases() {
  local schema="$1"

  if ! command -v jq >/dev/null 2>&1; then
    echo "Schema mode needs jq (on Ubuntu: sudo apt install jq)." >&2
    return 2
  fi
  if [[ ! -r "${schema}" ]]; then
    echo "Cannot read ${schema}." >&2
    return 2
  fi
  if ! jq -e '.paths | type == "object"' "${schema}" >/dev/null 2>&1; then
    echo "${schema} is not an OpenAPI JSON document with a paths object." >&2
    echo "(YAML? Convert it first: yq -o=json file.yaml > file.json)" >&2
    return 2
  fi

  case_base="${BASE_URL:-$(jq -r '.servers[0].url // empty' "${schema}")}"
  case_base="${case_base%/}"
  if [[ -z "${case_base}" || "${case_base}" == *"{"* ]]; then
    echo "Set BASE_URL: ${schema} has no usable servers[0].url." >&2
    return 2
  fi

  if [[ "${SKIP_MTLS}" != "on" && -n "${API_CLIENT_CERT}" && -n "${API_CLIENT_KEY}" ]]; then
    case_extra_args=(--cert "${API_CLIENT_CERT}" --key "${API_CLIENT_KEY}")
  fi

  jq -r "${SCHEMA_CASES_JQ}" "${schema}" > "${WORK_DIR}/cases"
  local -a lines
  mapfile -t lines < "${WORK_DIR}/cases"

  # Every operation yields exactly one compliant ("origin") case, run or skipped.
  local line kind name expected method target body operations=0
  for line in "${lines[@]}"; do
    IFS=$'\x1f' read -r kind name expected _ <<< "${line}"
    if [[ "${expected}" == "origin" ]]; then
      operations=$((operations + 1))
    fi
    if (( ${#name} + 2 > case_width )); then
      case_width=$(( ${#name} + 2 ))
    fi
  done

  printf 'Schema %s: %d operation(s), %d case(s), sent to %s\n\n' \
    "${schema}" "${operations}" "${#lines[@]}" "${case_base}"
  print_header

  for line in "${lines[@]}"; do
    IFS=$'\x1f' read -r kind name expected method target body <<< "${line}"
    if [[ "${kind}" == "skip" ]]; then
      skip_case "${name}" "${expected}" "${body}"
    else
      run_case "${name}" "${expected}" "${method}" "${target}" "${body}"
    fi
  done
}

# The built-in Juice Shop and go-httpbin cases.
run_builtin_cases() {
  print_header

  # Login: type confusion and SQL injection bypass (Juice Shop "Login Admin").
  run_case "login: valid payload"            origin     POST "/rest/user/login" \
    '{"email":"demo@juice-sh.op","password":"wrong"}'
  run_case "login: email is a number"        edge-block POST "/rest/user/login" \
    '{"email":12345,"password":"x"}'
  run_case "login: missing password"         edge-block POST "/rest/user/login" \
    '{"email":"demo@juice-sh.op"}'
  run_case "login: SQLi in email"            edge-block POST "/rest/user/login" \
    "{\"email\":\"' OR 1=1--\",\"password\":\"x\"}"

  # Product lookup: path parameter must be a positive integer.
  run_case "product: numeric id"             origin     GET "/api/Products/1"
  run_case "product: non-numeric id"         edge-block GET "/api/Products/abc"

  # Search: free-text query restricted to a safe character set.
  run_case "search: plain term"              origin     GET "/rest/products/search?q=apple"
  run_case "search: UNION-based SQLi"        edge-block GET \
    "/rest/products/search?q=qwert%27%29%29%20UNION%20SELECT%20id%20FROM%20Users--"

  # Basket: negative quantity (Juice Shop "Payback Time").
  run_case "basket: quantity 1"              origin     POST "/api/BasketItems/" \
    '{"ProductId":1,"BasketId":"1","quantity":1}'
  run_case "basket: negative quantity"       edge-block POST "/api/BasketItems/" \
    '{"ProductId":1,"BasketId":"1","quantity":-100}'

  # Feedback: zero-star rating (Juice Shop "Zero Stars").
  run_case "feedback: rating 5"              origin     POST "/api/Feedbacks/" \
    '{"captchaId":0,"captcha":"0","comment":"Great shop","rating":5}'
  run_case "feedback: rating 0"              edge-block POST "/api/Feedbacks/" \
    '{"captchaId":0,"captcha":"0","comment":"Zero stars","rating":0}'

  # Front-end calls with nothing for a schema to check. They are controls:
  # tightening enforcement must not break them.
  run_case "captcha: fetch"                  origin     GET "/rest/captcha/"
  run_case "socket.io: polling handshake"    origin     GET \
    "/socket.io/?EIO=4&transport=polling"

  # Fallthrough: a path that matches no saved endpoint.
  if [[ "${FALLTHROUGH}" == "on" ]]; then
    run_case "undeclared endpoint"           edge-block GET "/api/zzz-undeclared"
  else
    skip_case "undeclared endpoint" edge-block "set FALLTHROUGH=on"
  fi

  # go-httpbin demo API (httpbin-api.yaml). /anything/* echoes any request
  # with 200, so every non-200 here comes from Cloudflare.
  if [[ -z "${API_BASE_URL}" ]]; then
    skip_case "httpbin API: all cases" "-" "set API_BASE_URL"
  else
    case_base="${API_BASE_URL}"

    # Query parameter: page must be an integer from 1 to 100.
    run_case "httpbin: page 1"               origin     GET "/get?page=1"
    run_case "httpbin: page out of range"    edge-block GET "/get?page=500"
    run_case "httpbin: page is not a number" edge-block GET "/get?page=abc"

    # Order body: SKU format, quantity range, and no undeclared fields.
    run_case "order: valid"                  origin     POST "/anything/orders" \
      '{"sku":"ABC-1234","quantity":2,"customer_email":"buyer@example.com"}'
    run_case "order: negative quantity"      edge-block POST "/anything/orders" \
      '{"sku":"ABC-1234","quantity":-5}'
    run_case "order: malformed SKU"          edge-block POST "/anything/orders" \
      '{"sku":"abc-1","quantity":1}'
    run_case "order: undeclared field"       edge-block POST "/anything/orders" \
      '{"sku":"ABC-1234","quantity":1,"unit_price":0}'

    # Order lookup: path parameter must be a positive integer.
    run_case "order: numeric id"             origin     GET "/anything/orders/42"
    run_case "order: non-numeric id"         edge-block GET "/anything/orders/abc"

    # Partner resource: slug format. The route also requires a client
    # certificate, so without one both cases would be refused by mTLS instead.
    if [[ "${SKIP_MTLS}" == "on" ]]; then
      skip_case "partner: valid / malformed slug" "-" "SKIP_MTLS=on"
    elif [[ -n "${API_CLIENT_CERT}" && -n "${API_CLIENT_KEY}" ]]; then
      case_extra_args=(--cert "${API_CLIENT_CERT}" --key "${API_CLIENT_KEY}")
      run_case "partner: valid slug"         origin     GET "/anything/partner/acme-corp"
      run_case "partner: malformed slug"     edge-block GET "/anything/partner/Acme_Corp"
      case_extra_args=()
    else
      skip_case "partner: valid / malformed slug" "-" "set API_CLIENT_CERT/KEY"
    fi

    case_base="${BASE_URL}"
  fi
}

main() {
  if [[ -n "${SCHEMA_FILE}" ]]; then
    run_schema_cases "${SCHEMA_FILE}"
  else
    run_builtin_cases
  fi

  printf '\n%d case(s) did not match the expected outcome.\n' "${failures}"
  [[ "${failures}" -eq 0 ]]
}

main "$@"
